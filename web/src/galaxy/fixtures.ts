import type { GalaxyCluster, GalaxyData, OperatingPoint } from "./types";

function cluster(
  id: string,
  title: string,
  priority: number,
  ask: number,
  act: number,
  cells: { act: number; ask: number; advisor: number; wait: number; tpShare: number },
  ops: OperatingPoint[],
  missed: number,
  precision: number,
  recall: number,
  precisionAct: number,
): GalaxyCluster {
  const split = (state: string, n: number) => {
    const tp = Math.round(n * cells.tpShare);
    return [
      { state, truth: "tp" as const, n: tp },
      { state, truth: "fp" as const, n: n - tp },
    ];
  };
  return {
    moment_id: id,
    title,
    custom: false,
    priority,
    thresholds: { ask, act },
    cells: [
      ...split("act", cells.act),
      ...split("ask", cells.ask),
      ...split("advisor", cells.advisor),
      { state: "wait", truth: "any", n: cells.wait },
    ],
    missed,
    operating_points: ops,
    precision,
    recall,
    precision_act: precisionAct,
  };
}

